'use strict';
const assert=require('node:assert/strict');
const {webkit,devices}=require('playwright');
(async()=>{
 const browser=await webkit.launch({headless:true});
 const page=await browser.newPage({...devices['iPhone 13'],locale:'en-US'});
 const step=4*60*60*1000,start=Date.now()-190*step;
 const candles=Array.from({length:180},(_,i)=>{
  const t=start+i*step,open=.04+i*.00006,close=open+(i%3===0?-.00002:.00004);
  return [t,String(open),String(Math.max(open,close)+.00009),String(Math.min(open,close)-.00009),String(close),'125000',t+step-1];
 });
 await page.route('**/api/v3/klines?**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(candles)}));
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.HOME_URL||'http://127.0.0.1:4173/index.html',{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>!!window.DeepRiseStructureChart&&!!window.DeepRiseStructure,{timeout:25000});
 await page.evaluate(()=>{
  const p=document.getElementById('chartPanel');
  p.classList.add('active','dr-view-structure');
  return window.DeepRiseStructureChart.load('TESTUSDT','4h');
 });
 await page.waitForFunction(()=>!!window.DeepRiseStructureChart.state.result,{timeout:25000});
 const layer=k=>page.evaluate(k=>window.DeepRiseStructureChart.state.layers[k],k);
 assert.equal(await layer('rsi'),false,'Mobile structure preset hides RSI by default to prioritize price');
 await page.evaluate(()=>window.DeepRiseStructureChart.setPreset('structure'));
 assert.equal(await layer('rsi'),false,'Structure preset hides RSI until enabled');
 await page.locator('#drStructurePanel .dr-fast-toggles [data-toggle-indicator="rsi"]').tap();
 assert.equal(await layer('rsi'),true,'Touch must enable RSI');
 assert.match(await page.locator('[data-indicator-feedback]').textContent(),/ON.*RSI/i);
 await page.locator('#drStructurePanel .dr-fast-toggles [data-toggle-indicator="orderBlocks"]').tap();
 assert.equal(await layer('orderBlocks'),false,'Touch must disable order blocks');
 await page.evaluate(()=>{
  window.__beforeFullscreenSvg=document.querySelector('#drStructurePanel svg[data-dr-interactive]');
  window.__beforeFullscreenToolbar=document.querySelector('#drStructurePanel .dr-draw-toolbar');
 });
 await page.locator('#drStructurePanel [data-structure-fullscreen]').tap();
 assert.equal(await page.evaluate(()=>window.DeepRiseStructureChart.state.expanded),true);
 assert.equal(await page.evaluate(()=>document.querySelector('#drStructurePanel svg[data-dr-interactive]')===window.__beforeFullscreenSvg),true,'Opening fullscreen must keep the existing SVG');
 assert.equal(await page.evaluate(()=>document.querySelector('#drStructurePanel .dr-draw-toolbar')===window.__beforeFullscreenToolbar),true,'Opening fullscreen must preserve active drawing controls');
 await page.waitForTimeout(800);
 assert.equal(await page.evaluate(()=>window.DeepRiseStructureChart.state.expanded),true,'Fullscreen must not close itself after the iPhone tap');
 assert.equal(await page.evaluate(()=>document.getElementById('drStructurePanel').parentElement===document.body),true,'Fullscreen must portal to body');
 await page.locator('#drStructurePanel .dr-fast-toggles [data-toggle-indicator="bollinger"]').tap();
 assert.equal(await layer('bollinger'),true,'Indicators must remain tappable in fullscreen');
 await page.evaluate(()=>window.DeepRiseStructureChart.setPreset('advanced'));
 assert.equal(await page.evaluate(()=>window.DeepRiseStructureChart.state.priceFocus),false,'Fullscreen must not silently hide enabled study panes');
 const extra=page.locator('#drStructurePanel .dr-extra-indicators');
 await extra.locator('summary').tap();
 assert.equal(await extra.evaluate(el=>el.open),true,'Advanced indicators drawer must open in fullscreen');
 const extensionBefore=await layer('extensions');
 await extra.locator('[data-toggle-indicator="extensions"]').tap();
 assert.equal(await layer('extensions'),!extensionBefore,'Extension study must toggle inside fullscreen');
 await extra.locator('[data-toggle-indicator="extensions"]').tap();
 assert.equal(await layer('extensions'),extensionBefore,'Extension study must restore');
 await extra.locator('summary').tap();
 assert.equal(await extra.evaluate(el=>el.open),false,'Advanced indicator drawer must close without closing fullscreen');
 for(const indicator of ['ema20','ema50','ema200','rsi','macd','atr','poc','volumeProfile','orderBlocks','fvg','fib']){
  console.log('Touch indicator:',indicator);
  const before=await layer(indicator);
  await page.locator('#drStructurePanel .dr-fast-toggles [data-toggle-indicator="'+indicator+'"]').tap();
  assert.equal(await layer(indicator),!before,indicator+' must toggle on tap in fullscreen');
  await page.locator('#drStructurePanel .dr-fast-toggles [data-toggle-indicator="'+indicator+'"]').tap();
  assert.equal(await layer(indicator),before,indicator+' must restore on second tap');
 }
 assert.ok(await page.locator('#drStructurePanel svg path[stroke="#bba2ff"]').count(),'Active RSI needs a visible plot after entering fullscreen');
 assert.ok(await page.locator('#drStructurePanel svg path[stroke="#e2a4f1"]').count(),'Active ATR needs a visible plot after entering fullscreen');
 await page.locator('#drStructurePanel [data-structure-fullscreen]').tap();
 assert.equal(await page.evaluate(()=>document.getElementById('drStructurePanel').parentElement.id),'chartPanel');
 await page.locator('#drStructurePanel [data-chart-zoom=".75"]').tap();
 assert.ok((await page.evaluate(()=>window.DeepRiseStructureChart.state.view.count))<40,'Touch zoom works');
 console.log('iPhone HOME chart: fullscreen persistence, preserved SVG, 12 indicators including advanced drawer, drawing toolbar and zoom PASS');
 if(errors.some(e=>/structure-chart|DeepRiseStructureChart/i.test(e)))throw Error(errors.join('\n'));
 await browser.close();
})().catch(e=>{console.error('iPhone scanner chart E2E failed:',e);process.exit(1)});
